-- A row for every version of a user, so it keeps users removed from the workspace.
CREATE TABLE IF NOT EXISTS trinocicd.slack.users (
    id varchar,
    team_id varchar,
    name varchar,
    deleted boolean,
    color varchar,
    real_name varchar,
    tz varchar,
    tz_label varchar,
    tz_offset integer,
    avatar_hash varchar,
    status_text varchar,
    status_emoji varchar,
    profile_real_name varchar,
    display_name varchar,
    real_name_normalized varchar,
    display_name_normalized varchar,
    email varchar,
    image_24 varchar,
    image_32 varchar,
    image_48 varchar,
    image_72 varchar,
    image_192 varchar,
    image_512 varchar,
    team varchar,
    is_admin boolean,
    is_owner boolean,
    is_primary_owner boolean,
    is_restricted boolean,
    is_ultra_restricted boolean,
    is_bot boolean,
    updated timestamp(6) with time zone,
    is_app_user boolean,
    has_2fa boolean
);
