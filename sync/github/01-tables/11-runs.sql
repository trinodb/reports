CREATE TABLE IF NOT EXISTS trinocicd.github.runs (
    owner varchar,
    repo varchar,
    id bigint,
    name varchar,
    node_id varchar,
    check_suite_id bigint,
    check_suite_node_id varchar,
    head_branch varchar,
    head_sha varchar,
    path varchar,
    run_number bigint,
    run_attempt bigint,
    event varchar,
    status varchar,
    conclusion varchar,
    workflow_id bigint,
    display_title varchar,
    actor_id bigint,
    actor_login varchar,
    triggering_actor_login varchar,
    pull_request_numbers array(bigint),
    created_at timestamp(6),
    updated_at timestamp(6),
    run_started_at timestamp(6)
);
