CREATE TABLE IF NOT EXISTS trinocicd.github.pulls (
    owner varchar,
    repo varchar,
    id bigint,
    node_id varchar,
    url varchar,
    html_url varchar,
    number bigint,
    state varchar,
    locked boolean,
    title varchar,
    user_id bigint,
    user_login varchar,
    body varchar,
    label_names array(varchar),
    milestone_id bigint,
    milestone_title varchar,
    active_lock_reason varchar,
    created_at timestamp(6),
    updated_at timestamp(6),
    closed_at timestamp(6),
    merged_at timestamp(6),
    merge_commit_sha varchar,
    assignee_id bigint,
    assignee_login varchar,
    assignee_logins array(varchar),
    requested_reviewer_logins array(varchar),
    head_ref varchar,
    head_sha varchar,
    base_ref varchar,
    base_sha varchar,
    author_association varchar,
    draft boolean,
    auto_merge_method varchar
);
