CREATE TABLE IF NOT EXISTS trinocicd.github.issues (
    owner varchar,
    repo varchar,
    id bigint,
    node_id varchar,
    url varchar,
    html_url varchar,
    number bigint,
    state varchar,
    state_reason varchar,
    title varchar,
    body varchar,
    user_id bigint,
    user_login varchar,
    labels array(varchar),
    assignee_id bigint,
    assignee_login varchar,
    assignee_logins array(varchar),
    milestone_id bigint,
    milestone_title varchar,
    locked boolean,
    active_lock_reason varchar,
    comments bigint,
    pull_request_url varchar,
    pull_request_merged_at timestamp(6),
    closed_at timestamp(6),
    created_at timestamp(6),
    updated_at timestamp(6),
    closed_by_id bigint,
    closed_by_login varchar,
    author_association varchar,
    draft boolean,
    reactions_total_count bigint,
    type_name varchar
);
